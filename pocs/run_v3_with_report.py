"""Run v3 pipeline on zipp with report + PoC output to pocs/."""
import os, sys, logging, json, time, re
from pathlib import Path
from typing import Any

os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, '.')

# Force rich terminal output
import rich.console
_orig_init = rich.console.Console.__init__
def _patched_init(self, *a, **kw):
    kw['force_terminal'] = True
    return _orig_init(self, *a, **kw)
rich.console.Console.__init__ = _patched_init

logging.basicConfig(level=logging.WARNING, stream=sys.stderr,
                    format='%(levelname)s:%(message)s')

from agies.engine.v3.runner import run_v3_pipeline
from agies.engine.v3.aggregator.models import AgentPhaseResult
from agies.engine.v3.aggregator.blackboard import BlackboardAggregator

TARGET = "/tmp/bounty_test/zipp_src/zipp-45b7f675c0bcaa4f3f9d15b4399fc71e74f2408c"
OUTPUT_DIR = Path("/home/xcy/workSpace/code-agies/pocs")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# ── Patch blackboard and phase_results capture ──
global_captured_results = []

# Patch BlackboardAggregator.record_phase_result to capture
_orig_record = BlackboardAggregator.record_phase_result
def _patched_record(self, result, **kw):
    global_captured_results.append(result)
    return _orig_record(self, result, **kw)
BlackboardAggregator.record_phase_result = _patched_record

print("=" * 60, flush=True)
print("  v3 Pipeline Audit Report", flush=True)
print("  Target: zipp (ZIP Slip CVE)", flush=True)
print("=" * 60, flush=True)

start = time.time()

try:
    run_v3_pipeline(
        target=TARGET,
        model="deepseek-chat",
        verbose=True,
        max_exploit=5,
        max_explore=3,
    )
except Exception as e:
    print(f"\n[ERROR] {e}", flush=True)

elapsed = time.time() - start

# ── Generate report ──
print(f"\n{'=' * 60}", flush=True)
print(f"  Generating report ({len(global_captured_results)} phase results)...", flush=True)
print(f"{'=' * 60}", flush=True)

report_path = OUTPUT_DIR / "v3_audit_report_zipp.md"
poc_path = OUTPUT_DIR / "v3_audit_findings_zipp.json"

# Build the report
lines = []
lines.append("# v3 Pipeline Audit Report — zipp")
lines.append("")
lines.append(f"> **Target:** `{TARGET}`")
lines.append(f"> **Date:** {time.strftime('%Y-%m-%d %H:%M:%S')}")
lines.append(f"> **Duration:** {elapsed:.0f}s")
lines.append(f"> **Model:** deepseek-chat")
lines.append("")

# Phase results
vuln_count = sum(1 for r in global_captured_results if r.is_vulnerable)
conf_high = sum(1 for r in global_captured_results if r.is_vulnerable and r.confidence and r.confidence >= 7)
conf_med = sum(1 for r in global_captured_results if r.is_vulnerable and r.confidence and 4 <= r.confidence < 7)
conf_low = sum(1 for r in global_captured_results if r.is_vulnerable and r.confidence and r.confidence < 4)

lines.append("## Summary")
lines.append("")
lines.append(f"| Metric | Value |")
lines.append(f"|--------|-------|")
lines.append(f"| Total paths discovered | {len(global_captured_results)} |")
lines.append(f"| Vulnerable findings | {vuln_count} |")
lines.append(f"| High confidence (≥7) | {conf_high} |")
lines.append(f"| Medium confidence (4-6) | {conf_med} |")
lines.append(f"| Low confidence (<4) | {conf_low} |")
lines.append("")

if vuln_count > 0:
    lines.append("## Findings")
    lines.append("")
    for i, r in enumerate(global_captured_results):
        if not r.is_vulnerable:
            continue
        vt = r.actual_vuln_type or r.vuln_type
        lines.append(f"### {i+1}. {r.path_id} ({vt})")
        lines.append("")
        lines.append(f"- **Path:** `{r.path_id}`")
        lines.append(f"- **Type:** {r.vuln_type}")
        lines.append(f"- **Score:** {r.score}")
        lines.append(f"- **Confidence:** {r.confidence}/10")
        lines.append(f"- **Vulnerable:** {r.is_vulnerable}")
        lines.append("")
        if r.analysis:
            lines.append(f"**Analysis:**")
            lines.append("")
            lines.append("```")
            lines.append(r.analysis[:500])
            if len(r.analysis) > 500:
                lines.append("... (truncated)")
            lines.append("```")
            lines.append("")

lines.append("## Recommendations")
lines.append("")
lines.append("Based on the v3 pipeline analysis:")
lines.append("")
for r in global_captured_results:
    if r.is_vulnerable and r.confidence and r.confidence >= 7:
        lines.append(f"- **High priority:** `{r.path_id}` — {r.vuln_type} (confidence: {r.confidence}/10)")
    elif r.is_vulnerable:
        lines.append(f"- **Medium priority:** `{r.path_id}` — {r.vuln_type} (confidence: {r.confidence}/10)")

lines.append("")
lines.append(f"---")
lines.append(f"*Generated by agies v3 pipeline in {elapsed:.0f}s*")
lines.append("")

report_content = "\n".join(lines)
report_path.write_text(report_content)

# Save findings JSON
findings_data = []
for r in global_captured_results:
    findings_data.append({
        "path_id": r.path_id,
        "vuln_type": r.vuln_type,
        "actual_vuln_type": r.actual_vuln_type,
        "score": r.score,
        "confidence": r.confidence,
        "is_vulnerable": r.is_vulnerable,
        "analysis_snippet": (r.analysis or "")[:300],
    })
poc_path.write_text(json.dumps(findings_data, indent=2, ensure_ascii=False))

# Check for existing PoC files
poc_files = list(OUTPUT_DIR.glob("*.py"))
lines = report_content.split("\n")
lines.insert(-2, "")  # Add blank line before footer
lines.insert(-2, "### Generated PoC Scripts")
lines.insert(-2, "")
for pf in sorted(poc_files):
    if pf.name != "run_v3.py":
        relative = pf.relative_to(OUTPUT_DIR.parent)
        lines.insert(-2, f"- `{relative}`")
lines.insert(-2, "")
report_path.write_text("\n".join(lines))

print(f"\n  Report: {report_path}", flush=True)
print(f"  Findings JSON: {poc_path}", flush=True)
print(f"  PoC scripts: {len(poc_files)-1} existing + new this run", flush=True)
print(f"\n  Pipeline completed in {elapsed:.0f}s", flush=True)
print(f"{'=' * 60}", flush=True)
